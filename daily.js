/* ============================================================
   R3D Daily Review — engine (simple + practical, Arabic RTL)

   Loads window.R3D_DAILY (generated by tools/build.py from
   library/content-data.json). Runs on BOTH pages:

     index.html  — home: stats, mode, level, time, categories, START
     review.html — flashcard review: flip, 🔊 play, ✓ know / ✗ dunno, timer

   Layout is a plain display toggle (no 3D transforms — iOS-safe).
   ============================================================ */
(function () {
  'use strict';

  var D = window.R3D_DAILY;
  if (!D || !D.cards.length) return;

  var CAT = {};
  D.cats.forEach(function (c) { CAT[c.id] = c; });

  // translations (Arabic, very short)
  var T = {
    lv: { easy: 'سهل', medium: 'متوسط', hard: 'صعب' },
    label: { street: 'شارعي', academic: 'رسمي', neutral: 'محايد' }
  };

  // localStorage keys
  var LS = {
    S: 'r3d-daily:state', Q: 'r3d-daily:queue',
    MK: 'r3d-daily:marks', TD: 'r3d-daily:today', HD: 'r3d-daily:hdone'
  };

  // session state
  var ST = {
    mode: 'all',          // 'all' | 'today'
    level: 'easy',        // easy | medium | hard
    cat: null,            // null | 'all' | catId
    bs: 60,               // seconds per session
    queue: [],            // card ids in order
    marks: {},            // id -> 'know' | 'dunno'
    today: [],            // ids reviewed today
    done: 0,              // sessions finished
    notes: 0              // dunnos (cards repeated)
  };

  // card index built from the payload once
  var cards = {};
  D.cards.forEach(function (c) { cards[c.id] = c; });

  function lsGet(k) {
    try { return JSON.parse(localStorage.getItem(k)); } catch (e) { return null; }
  }
  function lsSet(k, v) {
    try { localStorage.setItem(k, JSON.stringify(v)); } catch (e) {}
  }
  function initLS() {
    lsSet(LS.S, JSON.stringify({ mode: ST.mode, level: ST.level, bs: ST.bs }));
    lsSet(LS.Q, JSON.stringify(ST.queue));
    lsSet(LS.MK, JSON.stringify(ST.marks));
    lsSet(LS.TD, JSON.stringify(ST.today));
    lsSet(LS.HD, '0');
  }
  function load() { initLS(); }
  function save() {
    lsSet(LS.S, JSON.stringify({ mode: ST.mode, level: ST.level, bs: ST.bs }));
    lsSet(LS.Q, JSON.stringify(ST.queue));
    lsSet(LS.MK, JSON.stringify(ST.marks));
    lsSet(LS.TD, JSON.stringify(ST.today));
    lsSet(LS.HD, String(parseInt(lsGet(LS.HD)) || 0) + 1);
  }

  function card(id) { return cards[id] || null; }

  function filtered() {
    var arr = D.cards.filter(function (c) { return c.level === ST.level; });
    if (ST.cat !== null && ST.cat !== 'all') {
      arr = arr.filter(function (c) { return c.cat === ST.cat; });
    }
    return arr;
  }

  function buildQueue() {
    var arr = filtered();
    if (ST.mode === 'today') {
      arr = arr.filter(function (c) { return ST.today.indexOf(c.id) > -1; });
      if (!arr.length) arr = filtered();          // fallback -> all of the level
    }
    // a session is `bs` seconds; ~3 cards per 10s -> cap cards accordingly
    var cap = Math.max(1, Math.min(80, Math.floor(ST.bs / 3)));
    return arr.slice(0, cap).map(function (c) { return c.id; });
  }

  function el(id) { return document.getElementById(id); }

  /* ---------------- DOM refs ---------------- */
  var audioEl = document.createElement('audio');
  audioEl.preload = 'auto';
  var cardEl = el('dcard'), frontEl = el('dfront'), backEl = el('dback');
  var timerEl = el('timer'), statEl = el('dstat');
  var pool = { know: el('btnKnow'), dunno: el('btnDunno'),
               spk: el('btnSpk'), flip: el('btnFlip'),
               end: el('btnEnd') };

  /* ---------------- render helpers ---------------- */
  function badge(c) {
    return '<span class="dbadge badge-' + c.label + '">' + T.label[c.label] + '</span>';
  }
  function frontHtml(c) {
    return '<div class="dzh">' + c.front + '</div>' +
      '<div class="dpy">' + c.py + '</div>' +
      '<div class="dar">' + c.ar + '</div>';
  }
  function backHtml(c) {
    var note = c.note ? '<div class="dnote">' + c.note + '</div>' : '';
    var pair = '';
    if (c.pair && card(c.pair)) {
      var p = card(c.pair);
      pair = '<div class="dpair"><b>مُكافَئَة:</b> ' + p.front + ' <span class="pinyin">' + p.py + '</span> — ' + p.ar + '</div>';
    }
    return badge(c) +
      '<div class="dar">' + c.ar + '</div>' +
      '<div class="dpy">' + c.py + '</div>' +
      note + pair;
  }
  function statAll(n) { return '<div class="stat"><b>' + n + '</b><span>إجمالي البطاقات</span></div>'; }
  function statToday(n) { return '<div class="stat"><b>' + n + '</b><span>في اليومانية</span></div>'; }
  function statMst(n) { return '<div class="stat"><b>' + n + '</b><span>معروفة</span></div>'; }

  /* ---------------- session ---------------- */
  var timerId = null;
  var deadline = 0;
  var curId = null;

  function tick() {
    var left = Math.max(0, Math.ceil((deadline - Date.now()) / 1000));
    timerEl.textContent = left + ' ثانية متبقية';
    if (left <= 0) endSession();
  }
  function startTimer() {
    if (timerId) clearInterval(timerId);
    deadline = Date.now() + ST.bs * 1000;
    tick();
    timerId = setInterval(tick, 1000);
  }
  function endSession() {
    if (timerId) { clearInterval(timerId); timerId = null; }
    statEl.innerHTML = statAll(ST.knows() + ST.dunnos()) + statToday(ST.today.length) +
      '<div class="stat"><b>' + ST.done + '</b><span>دفعة مكتملة</span></div>';
    cardEl.className = 'dcard';
    cardEl.innerHTML = '<div class="empty">' +
      '<p><strong>نهاية الدفعة</strong> — ' + ST.queue.length + ' بطاقة خضتها، ' +
      ST.knows() + ' عرفها، ' + ST.dunnos() + ' لسه أراجعها</p>' +
      '<p><a class="btn home" href="index.html">الرئيسية</a></p>' +
      '</div>';
  }
  function queuePresent() {
    return ST.queue.slice().concat(curId !== null ? [curId] : []);
  }
  function knows() { return countST('know'); }
  function dunnos() { return countST('dunno'); }
  function countST(k) {
    return queuePresent().filter(function (id) { return ST.marks[id] === k; }).length;
  }

  function startSession() {
    ST.queue = buildQueue();
    ST.done = 0; ST.notes = 0;
    if (!ST.queue.length) {
      cardEl.innerHTML = '<div class="empty"><p><strong>ما في كلمات في المستوى هذا</strong></p><p>غيّر المستوى أو الفئة.</p></div>';
      return;
    }
    ST.today = arrayUnique(ST.today.concat(ST.queue));
    ST.marks = {};
    ST.done++;
    save();
    curId = ST.queue.shift();
    timerEl.textContent = ST.bs + ' ثانية متبقية';
    cardEl.className = 'dcard';
    renderCard();
    startTimer();
  }

  function nextCard() {
    if (ST.queue.length === 0) { endSession(); return; }
    curId = ST.queue.shift();
    ST.today = arrayUnique(ST.today.concat([curId]));
    save();
    renderCard();
  }

  function answer(kind) {
    if (!curId) return;
    if (kind === 'know') { ST.marks[curId] = 'know'; ST.done++; }
    else { ST.marks[curId] = 'dunno'; ST.notes++; }
    save();
    var i = ST.queue.indexOf(curId);
    if (i > -1) ST.queue.splice(i, 1);
    curId = null;
    cardEl.className = 'dcard';
    frontEl.innerHTML = backEl.innerHTML = '';
    nextCard();                                     // auto-advance
  }

  function flip() {
    if (!curId) return;
    cardEl.className = cardEl.className === 'dcard' ? 'dcard flipped' : 'dcard';
  }

  function arrayUnique(a) { return Array.from(new Set(a)); }

  /* ---------------- rendering the current card ---------------- */
  function renderCard() {
    var c = card(curId);
    if (!c) {
      cardEl.innerHTML = '<div class="empty"><p><strong>ما في كلمات للمراجعة الآن</strong></p><p><a class="btn" href="index.html">رجوع للقائمة</a></div>';
      return;
    }
    frontEl.innerHTML = frontHtml(c);
    backEl.innerHTML = backHtml(c);
    cardEl.className = 'dcard' + (cardEl.className.indexOf('flipped') === -1 ? '' : ' flipped');
  }

  function renderStat() {
    statEl.innerHTML = statAll(D.cards.length) + statToday(ST.today.length) + statMst(0);
  }

  /* ---------------- category chips (home page) ---------------- */
  function renderCats() {
    var box = el('catCh');
    var html = '<button class="dchip on" data-cat="all">📋 الكل</button>';
    D.cats.forEach(function (c) {
      html += '<button class="dchip" data-cat="' + c.id + '">' + c.icon + ' ' + c.ar + '</button>';
    });
    box.innerHTML = html;
    box.querySelectorAll('.dchip').forEach(function (b) {
      b.addEventListener('click', function () {
        box.querySelectorAll('.dchip').forEach(function (x) { x.className = 'dchip' + (x === b ? ' on' : ''); });
        ST.cat = (b.dataset.cat === 'all') ? null : b.dataset.cat;
        if (ST.queue.length === 0) startSession();
      });
    });
  }

  /* ---------------- page init ---------------- */
  function init() {
    load();
    renderStat();

    // home page controls (index.html)
    var startBtn = el('startBtn');
    if (startBtn) {
      startBtn.addEventListener('click', function () {
        startSession();
        window.location.href = 'review.html';
      });
    }
    var resetBtn = el('resetBtn');
    if (resetBtn) {
      resetBtn.addEventListener('click', function () {
        ST.queue = []; ST.marks = {}; ST.today = []; ST.done = 0; ST.notes = 0;
        lsSet(LS.Q, JSON.stringify(ST.queue));
        lsSet(LS.MK, JSON.stringify(ST.marks));
        lsSet(LS.TD, JSON.stringify(ST.today));
        lsSet(LS.HD, '0');
        window.location.href = 'index.html';
      });
    }

    // review page controls (review.html) — only when not on home
    if (!startBtn) {
      pool.know.addEventListener('click', function () { answer('know'); });
      pool.dunno.addEventListener('click', function () { answer('dunno'); });
      pool.spk.addEventListener('click', function () {
        if (!curId) return;
        audioEl.src = 'audio/' + curId + '.mp3';
        audioEl.play().catch(function () { /* blocked - serve via local server */ });
      });
      pool.flip.addEventListener('click', flip);
      pool.end.addEventListener('click', function () {
        if (timerId) { clearInterval(timerId); timerId = null; }
        startSession();
      });
    }

    // mode / level / time selectors (home)
    el('modeToday').addEventListener('click', setMode('today'));
    el('modeAll').addEventListener('click', setMode('all'));
    var btns = el('dlev');
    if (btns) {
      Array.prototype.forEach.call(btns.querySelectorAll('button'), function (b) {
        b.addEventListener('click', function () { ST.level = b.dataset.lv; save(); });
      });
    }
    var bsBtns = el('dbs');
    if (bsBtns) {
      Array.prototype.forEach.call(bsBtns.querySelectorAll('button'), function (b) {
        b.addEventListener('click', function () { ST.bs = parseInt(b.dataset.bs, 10); save(); });
      });
    }
    // category chips (home page only)
    if (el('catCh')) renderCats();

    load();                                   // restore state
    setTimeout(init2, 120);
  }

  function init2() {
    if (ST.queue.length === 0) startSession();
  }

  function setMode(mode) {
    ST.mode = mode;
    save();
    el('modeToday').className = 'dcBtn' + (mode === 'today' ? ' on' : '');
    el('modeAll').className = 'dcBtn' + (mode === 'all' ? ' on' : '');
  }

  load();
  setTimeout(init, 200);
})();
